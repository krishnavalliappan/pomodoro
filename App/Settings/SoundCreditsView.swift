import PomodoroCore
import SwiftUI

/// Who made the bundled ambient recordings, under which license. CC BY needs exactly this.
struct SoundCreditsView: View {
    static let size = CGSize(width: 460, height: 640)

    var sounds: [AmbientSound]
    var onDone: () -> Void

    private var recorded: [AmbientSound] {
        sounds.filter { $0.credit != nil }
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            VStack(alignment: .leading, spacing: 4) {
                Text("Sound Credits")
                    .font(.headline)
                Text("Ambient recordings from Blanket, trimmed, loudness-matched and looped for Pomodoro. White, pink and brown noise are generated by Pomodoro.")
                    .font(.callout)
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
            .padding(16)
            Divider()
            ScrollView {
                VStack(alignment: .leading, spacing: 10) {
                    ForEach(recorded) { sound in
                        if let credit = sound.credit {
                            SoundCreditRow(sound: sound, credit: credit)
                        }
                    }
                }
                .padding(16)
                .frame(maxWidth: .infinity, alignment: .leading)
            }
            Divider()
            HStack {
                Spacer()
                Button("Done", action: onDone)
                    .keyboardShortcut(.defaultAction)
            }
            .padding(12)
        }
        .frame(width: Self.size.width, height: Self.size.height)
        .background(Color(nsColor: .windowBackgroundColor))
    }
}

private struct SoundCreditRow: View {
    var sound: AmbientSound
    var credit: AmbientCredit

    var body: some View {
        HStack(alignment: .firstTextBaseline, spacing: 10) {
            Image(systemName: sound.symbol)
                .frame(width: 20)
                .foregroundStyle(.secondary)
            VStack(alignment: .leading, spacing: 2) {
                Text(sound.title)
                    .fontWeight(.medium)
                Text("“\(credit.title)” by \(credit.author)\(editedBy)")
                    .foregroundStyle(.secondary)
                    .lineLimit(1)
                    .truncationMode(.middle)
                HStack(spacing: 8) {
                    Link("Source", destination: credit.url)
                    if let licenseURL = credit.licenseURL {
                        Link(credit.licenseName, destination: licenseURL)
                    } else {
                        Text(credit.licenseName)
                            .foregroundStyle(.secondary)
                    }
                }
            }
            .font(.callout)
        }
    }

    private var editedBy: String {
        credit.editedBy.map { ", edited by \($0)" } ?? ""
    }
}
